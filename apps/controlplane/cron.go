package main

import (
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"time"

	"github.com/riazulbd/serverpanel/packages/capabilities"
	"github.com/riazulbd/serverpanel/packages/proto"
)

// cronJob is what cron.list/cron.create return as JSON — kept in step with
// the agent-side type of the same shape (packages/capabilities/cron.go
// cronJob) since the crontab itself, not this control plane's database, is
// the source of truth for a site's scheduled jobs (there's nothing here to
// duplicate or get out of sync with — every read goes to the agent).
type cronJob struct {
	ID       string `json:"id"`
	Schedule string `json:"schedule"`
	Command  string `json:"command"`
}

// handleListCron dispatches cron.list for one site's system user.
func (a *apiServer) handleListCron(w http.ResponseWriter, r *http.Request) {
	actor := sessionFromContext(r.Context()).Email
	serverID := r.PathValue("id")
	siteID := r.PathValue("siteId")

	site, ok := a.store.getSite(serverID, siteID)
	if !ok {
		writeErr(w, http.StatusNotFound, "site not found")
		return
	}

	ctx, cancel := context.WithTimeout(r.Context(), 30*time.Second)
	defer cancel()

	ev, err := a.gw.dispatch(ctx, serverID, actor, capabilities.CapCronList, map[string]any{
		"system_user": site.SystemUser,
	})
	if err != nil {
		writeErr(w, http.StatusBadGateway, err.Error())
		return
	}
	if ev.Status != proto.TaskSucceeded {
		writeErr(w, http.StatusUnprocessableEntity, "cron.list failed on the agent: "+ev.Message)
		return
	}

	var result struct {
		Jobs []cronJob `json:"jobs"`
	}
	if err := json.Unmarshal([]byte(ev.Detail), &result); err != nil {
		writeErr(w, http.StatusInternalServerError, "cron.list returned a result that could not be parsed: "+err.Error())
		return
	}
	writeJSON(w, http.StatusOK, result.Jobs)
}

// handleCreateCron dispatches cron.create for one site's system user. The
// job ID is generated here (not by the caller or the agent) so it's always
// an opaque, collision-resistant identifier the agent's cronIDRe accepts —
// the same reason server/site/backup IDs are generated by the store rather
// than trusted from the request.
func (a *apiServer) handleCreateCron(w http.ResponseWriter, r *http.Request) {
	actor := sessionFromContext(r.Context()).Email
	serverID := r.PathValue("id")
	siteID := r.PathValue("siteId")

	site, ok := a.store.getSite(serverID, siteID)
	if !ok {
		writeErr(w, http.StatusNotFound, "site not found")
		return
	}

	var req struct {
		Schedule string `json:"schedule"`
		Command  string `json:"command"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil || req.Schedule == "" || req.Command == "" {
		writeErr(w, http.StatusBadRequest, "schedule and command are required")
		return
	}

	id := randID("cron")

	ctx, cancel := context.WithTimeout(r.Context(), 30*time.Second)
	defer cancel()

	ev, err := a.gw.dispatch(ctx, serverID, actor, capabilities.CapCronCreate, map[string]any{
		"system_user": site.SystemUser, "id": id, "schedule": req.Schedule, "command": req.Command,
	})
	if err != nil {
		writeErr(w, http.StatusBadGateway, err.Error())
		return
	}
	if ev.Status != proto.TaskSucceeded {
		writeErr(w, http.StatusUnprocessableEntity, "cron.create failed on the agent: "+ev.Message)
		return
	}

	var job cronJob
	if err := json.Unmarshal([]byte(ev.Detail), &job); err != nil {
		writeErr(w, http.StatusInternalServerError, "cron job was created on the agent but its result could not be parsed: "+err.Error())
		return
	}
	a.store.log(serverID, actor, "cron.created", fmt.Sprintf("site_id=%s cron_id=%s schedule=%q", siteID, job.ID, job.Schedule))
	writeJSON(w, http.StatusCreated, job)
}

// handleDeleteCron dispatches cron.delete for one site's system user and
// one cron job id, both scoped through the site record so a caller can
// never address a cron job on a system user it doesn't own by passing an
// arbitrary id.
func (a *apiServer) handleDeleteCron(w http.ResponseWriter, r *http.Request) {
	actor := sessionFromContext(r.Context()).Email
	serverID := r.PathValue("id")
	siteID := r.PathValue("siteId")
	cronID := r.PathValue("cronId")

	site, ok := a.store.getSite(serverID, siteID)
	if !ok {
		writeErr(w, http.StatusNotFound, "site not found")
		return
	}

	ctx, cancel := context.WithTimeout(r.Context(), 30*time.Second)
	defer cancel()

	ev, err := a.gw.dispatch(ctx, serverID, actor, capabilities.CapCronDelete, map[string]any{
		"system_user": site.SystemUser, "id": cronID,
	})
	if err != nil {
		writeErr(w, http.StatusBadGateway, err.Error())
		return
	}
	if ev.Status != proto.TaskSucceeded {
		writeErr(w, http.StatusUnprocessableEntity, "cron.delete failed on the agent: "+ev.Message)
		return
	}

	a.store.log(serverID, actor, "cron.deleted", fmt.Sprintf("site_id=%s cron_id=%s", siteID, cronID))
	writeJSON(w, http.StatusOK, map[string]string{"status": "deleted"})
}
